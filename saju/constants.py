def ganzhi_index(stem: int, branch: int) -> int:
    """천간·지지 번호를 60갑자 번호(갑자=0)로 변환."""
    for i in range(60):
        if i % 10 == stem and i % 12 == branch:
            return i
    raise ValueError("음양이 맞지 않는 간지 조합")
